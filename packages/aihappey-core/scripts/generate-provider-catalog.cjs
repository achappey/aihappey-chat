const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const Ajv = require("ajv");
const { parseTree } = require("jsonc-parser");

const packageRoot = path.resolve(__dirname, "..");
const providersRoot = path.join(packageRoot, "src/runtime/providers");
const catalogRoot = path.join(providersRoot, "catalog");
const outputFile = path.join(providersRoot, "catalog.generated.ts");
const schema = require("../src/runtime/providers/provider.schema.json");
const validate = new Ajv({ allErrors: true }).compile(schema);

function validateMetadata(metadata, filename) {
  assert.ok(validate(metadata), `Invalid provider metadata ${filename}: ${JSON.stringify(validate.errors)}`);
}

function parseJson(text, filename) {
  const errors = [];
  const tree = parseTree(text, errors, { disallowComments: true, allowTrailingComma: false });
  assert.ok(tree && errors.length === 0, `Invalid strict JSON in ${filename}`);
  function check(node) {
    if (node.type === "object") {
      const keys = new Set();
      for (const property of node.children ?? []) {
        const key = property.children[0].value;
        assert.ok(!keys.has(key), `Duplicate JSON property ${key} in ${filename}`);
        keys.add(key);
      }
    }
    for (const child of node.children ?? []) check(child);
  }
  check(tree);
  // Use native JSON semantics after duplicate/syntax checks (ordinary object prototypes).
  return JSON.parse(text);
}

function readCatalog(directory = catalogRoot) {
  const index = parseJson(fs.readFileSync(path.join(directory, "index.json"), "utf8"), "index.json");
  assert.ok(Array.isArray(index) && index.length > 0, "Catalog index must be a nonempty ordered array");
  const ids = new Set();
  const files = new Set();
  const entries = index.map((entry) => {
    assert.ok(entry && typeof entry === "object" && !Array.isArray(entry), "Invalid index entry");
    assert.deepEqual(Object.keys(entry).sort(), ["file", "id"], "Index entries must contain only id and file");
    assert.equal(typeof entry.id, "string");
    assert.match(entry.id, /^[a-z][a-z0-9]*$/, "Invalid provider ID");
    assert.notEqual(entry.id, "__proto__");
    assert.equal(typeof entry.file, "string");
    assert.match(entry.file, /^[a-z0-9][a-z0-9-]*\.json$/, "Provider file must be a local JSON filename");
    assert.notEqual(entry.file, "index.json", "Index cannot reference itself");
    assert.ok(!ids.has(entry.id), `Duplicate provider ID ${entry.id}`);
    assert.ok(!files.has(entry.file), `Duplicate provider file ${entry.file}`);
    ids.add(entry.id);
    files.add(entry.file);
    const metadata = parseJson(fs.readFileSync(path.join(directory, entry.file), "utf8"), entry.file);
    validateMetadata(metadata, entry.file);
    return { ...entry, metadata };
  });
  const actual = fs.readdirSync(directory).filter((file) => file.endsWith(".json") && file !== "index.json").sort();
  assert.deepEqual([...files].sort(), actual, "Unindexed or missing provider JSON files");
  return entries;
}

function generate(entries) {
  const imports = entries.map(({ file }, i) => `import provider${i} from "./catalog/${file}";`);
  const properties = entries.map(({ id }, i) => `  ${JSON.stringify(id)}: provider${i},`);
  // JSON imports widen literal strings; schema validation above enforces category/icon enums.
  return `// Generated by scripts/generate-provider-catalog.cjs. Do not edit.\n// Metadata source of truth: catalog/index.json and its referenced JSON files.\nimport type { Provider } from "aihappey-types";\n${imports.join("\n")}\n\nexport const PROVIDER_CATALOG = {\n${properties.join("\n")}\n} as Record<string, Omit<Provider, "createGatewayMetadata">>;\n`;
}

function main(args = process.argv.slice(2)) {
  const entries = readCatalog();
  const content = generate(entries);
  if (args.includes("--check")) {
    assert.equal(fs.readFileSync(outputFile, "utf8").replace(/\r\n/g, "\n"), content, "Generated provider imports are stale; run npm run generate:providers --workspace aihappey-core");
  } else if (!fs.existsSync(outputFile) || fs.readFileSync(outputFile, "utf8").replace(/\r\n/g, "\n") !== content) {
    fs.writeFileSync(outputFile, content, "utf8");
  }
  console.log(`Provider catalog ${args.includes("--check") ? "checked" : "generated"}: ${entries.length} JSON providers.`);
}

module.exports = { readCatalog, generate, validateMetadata, parseJson, main };
if (require.main === module) main();
