const fs = require("fs");
const path = require("path");

const packageRoot = path.resolve(__dirname, "..");
const pricingDir = path.join(packageRoot, "src", "runtime", "providers", "catalog", "pricing");
const outputFile = path.join(packageRoot, "src", "runtime", "providers", "catalog", "pricing.generated.ts");

const providerKeyFromFilename = (filename) => path.basename(filename, ".json").trim().toLowerCase();
const importNameForProviderKey = (providerKey) => `${providerKey.replace(/[^a-z0-9]+/g, "_") || "provider"}Pricing`;

const files = fs.existsSync(pricingDir)
  ? fs.readdirSync(pricingDir)
    .filter((filename) => filename.toLowerCase().endsWith(".json"))
    .sort((a, b) => a.localeCompare(b))
  : [];

const entries = files.map((filename) => ({
  filename,
  providerKey: providerKeyFromFilename(filename),
})).filter((entry) => entry.providerKey);

const seen = new Set();
const duplicates = entries.filter((entry) => {
  if (seen.has(entry.providerKey)) return true;
  seen.add(entry.providerKey);
  return false;
});

if (duplicates.length > 0) {
  throw new Error(`Duplicate pricing provider keys: ${duplicates.map((entry) => entry.providerKey).join(", ")}`);
}

const importLines = entries.map(({ filename, providerKey }) =>
  `import ${importNameForProviderKey(providerKey)} from "./pricing/${filename}";`
);

const recordLines = entries.map(({ providerKey }) =>
  `  ${JSON.stringify(providerKey)}: ${importNameForProviderKey(providerKey)},`
);

const content = `${importLines.join("\n")}

// This file is generated by scripts/generate-provider-pricing-index.cjs.
// Add a provider pricing JSON file under ./pricing and run the package build to update it.
export const PROVIDER_PRICING_CATALOGS = {
${recordLines.join("\n")}
} as const;
`;

fs.writeFileSync(outputFile, content, "utf8");

